// Writes public/_headers, the headers Cloudflare puts on the static pages, from
// the same list the middleware uses for the pages the Worker renders. Runs
// before every build (`prebuild`); the Cloudflare adapter adds its own cache
// rules for /_astro/* to the file afterwards.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import { securityHeaders } from "../src/lib/security-headers.js";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const DEST = resolve(root, "public/_headers");

const lines = [
	"# Generated by scripts/generate-headers.mjs from src/lib/security-headers.js.",
	"# Edit that file, not this one.",
	"/*",
	...Object.entries(securityHeaders).map(
		([name, value]) => `  ${name}: ${value}`,
	),
	"",
];
writeFileSync(DEST, lines.join("\n"));
console.log(`wrote ${DEST}`);
